#!/usr/bin/env python3
"""Regenerate the status block of README.md from the test gate and the timing ledger.

Runs `ultra_harness manifest` over tests/roms/manifest.txt, counts the outcomes per kind of
oracle, counts the ledger's parameters by confidence, and rewrites the text between the
STATUS:BEGIN / STATUS:END markers in README.md. Nothing in that block is typed by hand.

    python3 tools/progress.py [--build build/release] [--check]

--check exits 1 if README.md would change (for CI), without writing it.
"""

import argparse
import datetime
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "<!-- STATUS:BEGIN: generated by tools/progress.py; do not edit by hand -->"
END = "<!-- STATUS:END -->"


def bar(done, total, width=40):
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def manifest_kinds(path):
    kinds = {}
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].split()
        if len(line) >= 3:
            kinds[line[0]] = (line[1], line[2])
    return kinds


def run_gate(build, saved=None):
    if saved:
        stdout, stderr = pathlib.Path(saved).read_text(), ""
    else:
        harness = ROOT / build / "tests" / "ultra_harness"
        if not harness.exists():
            sys.exit(f"{harness} not found: build the preset first")
        out = subprocess.run(
            [str(harness), "manifest", str(ROOT / "tests/roms/manifest.txt"),
             "--rom-dir", str(ROOT / "tests/roms")],
            capture_output=True, text=True)
        stdout, stderr = out.stdout, out.stderr
    rows = {}
    summary = None
    for line in stdout.splitlines():
        m = re.match(r"(ok|BAD)\s+(\S+)\s+expected (\w+)\s+got (\w+)\s+(.*)", line)
        if m:
            rows[m.group(2)] = (m.group(1) == "ok", m.group(4) == "pass", m.group(5))
        m = re.match(r"(\d+) entries, (\d+) not as expected", line)
        if m:
            summary = (int(m.group(1)), int(m.group(2)))
    if summary is None:
        sys.exit("harness produced no summary:\n" + stdout + stderr)
    return rows, summary


def ledger_counts(path):
    text = path.read_text()
    params = text.split("## Parameters", 1)[1].split("## Expected-fail", 1)[0]
    counts = {}
    for line in params.splitlines():
        cells = [c.strip() for c in line.split("|")]
        if len(cells) > 5 and cells[1].startswith("`"):
            counts[cells[4]] = counts.get(cells[4], 0) + 1
    expected_fail = sum(1 for line in text.split("## Expected-fail", 1)[1].splitlines()
                        if line.startswith("| `"))
    return counts, expected_fail


def render(rows, summary, kinds, ledger, expected_fail):
    entries, bad = summary
    st = next(d for i, (_, _, d) in rows.items() if kinds[i][1] == "systemtest")
    # One "<group> failed N of M" per test group the ROM was built with.
    groups = re.findall(r"[\w-]+ failed (\d+) of (\d+)", st.split("\n")[0])
    st_fail, st_total = sum(int(f) for f, _ in groups), sum(int(t) for _, t in groups)
    screens = [(i, r) for i, r in rows.items() if kinds[i][1] == "screen"]
    screens_pass = sum(1 for _, r in screens if r[1])
    timing = [(i, r) for i, r in rows.items() if kinds[i][1] == "kromcount"]
    tol = [(i, r) for i, r in timing if not i.endswith("-exact")]
    exact = [(i, r) for i, r in timing if i.endswith("-exact")]
    worst = max((abs(float(x)) for _, r in tol for x in re.findall(r"([+-]\d+\.\d+)%", r[2].split("(")[0])),
                default=0.0)

    lines = [BEGIN, f"_Snapshot {datetime.date.today().isoformat()}._", "", "```"]
    lines += [
        "n64-systemtest  CPU, COP0, TLB, COP1 (Phase 0 scope; base, timing, cycle, CP0 hazards)",
        f"    {bar(st_total - st_fail, st_total)}  {100 * (st_total - st_fail) / st_total:5.1f}%"
        f"   {st_total - st_fail:,} / {st_total:,} tests pass",
        "krom CPUTest   framebuffer identical to the hardware screenshot",
        f"    {bar(screens_pass, len(screens))}  {100 * screens_pass / len(screens):5.1f}%"
        f"   {screens_pass} / {len(screens)} ROMs",
        "krom timing    loop counts vs hardware (CPU and CP1 TIMINGNTSC)",
        f"    {sum(1 for _, r in tol if r[1])} / {len(tol)} within 2%, worst {worst:.2f}%;"
        f" {sum(1 for _, r in exact if r[1])} / {len(exact)} within the hardware noise floor",
        "```",
        "",
        f"**Gate: {'green' if bad == 0 else 'RED'}.** {entries} manifest entries, {bad} not as "
        f"expected. The {len(screens) - screens_pass} screens that differ and the exact timing "
        f"entries are recorded as expected failures in the [ledger](docs/timing/ledger.md) with "
        f"the evidence for each ({expected_fail} entries); an unexpected pass fails the gate too.",
        "",
        "| Timing and behaviour parameters (ledger) | Count |",
        "|---|---|",
    ]
    for k in ("Measured", "Derived", "Guess", "Open", "Design"):
        if k in ledger:
            lines.append(f"| {k} | {ledger[k]} |")
    lines.append(END)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="build/release")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--from", dest="saved", help="read a saved `ultra_harness manifest` output "
                    "instead of running the gate")
    args = ap.parse_args()
    kinds = manifest_kinds(ROOT / "tests/roms/manifest.txt")
    rows, summary = run_gate(args.build, args.saved)
    ledger, expected_fail = ledger_counts(ROOT / "docs/timing/ledger.md")
    block = render(rows, summary, kinds, ledger, expected_fail)
    readme = ROOT / "README.md"
    text = readme.read_text()
    if BEGIN not in text or END not in text:
        sys.exit("README.md has no STATUS markers")
    new = text.split(BEGIN, 1)[0] + block + text.split(END, 1)[1]
    if args.check:
        same = re.sub(r"_Snapshot .*?_", "", new) == re.sub(r"_Snapshot .*?_", "", text)
        sys.exit(0 if same else 1)
    readme.write_text(new)
    print(block)


if __name__ == "__main__":
    main()
